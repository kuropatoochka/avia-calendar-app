_IDENTITY_VERSION = 1


def _compute_row_hash(
    *,
    flight_type: str,
    seats: int,
    city_from: str,
    city_to: str,
    has_sea: bool,
    has_warm: bool,
    has_nature: bool,
    company: str,
    plane_type: str,
    duration: int,
    departure_day: str,
    arrival_day: str,
    departure_time: time,
    arrival_time: time,
    booking_day_range: int,
) -> str:
    payload: dict[str, Any] = {
        "v": _IDENTITY_VERSION,
        "type": flight_type,
        "seats": seats,
        "city_from": city_from.strip(),
        "city_to": city_to.strip(),
        "has_sea": bool(has_sea),
        "has_warm": bool(has_warm),
        "has_nature": bool(has_nature),
        "company": company.strip(),
        "plane_type": plane_type.strip(),
        "duration": duration,
        "departure_day": departure_day.strip(),
        "arrival_day": arrival_day.strip(),
        "departure_time": departure_time.strftime("%H:%M:%S"),
        "arrival_time": arrival_time.strftime("%H:%M:%S"),
        "booking_day_range": booking_day_range,
    }
    canonical = json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True)
    return hashlib.sha256(canonical.encode("utf-8")).hexdigest()


